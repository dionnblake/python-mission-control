const knownTopics = new Set<Topic>([
  "variables",
  "strings",
  "conditionals",
  "collections",
  "loops",
  "functions",
  "exceptions",
  "other",
]);

/** Return actionable authoring errors without throwing on malformed entries. */
export function validateFlashcards(
  bank: unknown[] = flashcards,
  knownChallengeIds?: Iterable<string>,
): string[] {
  const errors: string[] = [];
  const ids = new Set<string>();
  const challengeIds = knownChallengeIds ? new Set(knownChallengeIds) : null;
  const add = (index: number, message: string) =>
    errors.push(`flashcards[${index}]: ${message}`);
  for (const [index, raw] of bank.entries()) {
    if (!raw || typeof raw !== "object" || Array.isArray(raw)) {
      add(index, "must be an object");
      continue;
    }
    const card = raw as Partial<Flashcard>;
    if (typeof card.id !== "string" || !card.id.trim()) add(index, "missing id");
    else if (ids.has(card.id)) add(index, "duplicate id");
    else ids.add(card.id);
    if (!knownTopics.has(card.topic as Topic)) add(index, "unknown topic");
    for (const field of ["concept", "front", "answer", "explanation"] as const)
      if (typeof card[field] !== "string" || !card[field]?.trim())
        add(index, `missing ${field}`);
    if (card.type !== "concept" && card.type !== "code")
      add(index, "invalid type");
    if (![1, 2, 3].includes(card.difficulty as number))
      add(index, "invalid difficulty");
    if (card.type === "code") {
      if (typeof card.code !== "string" || !card.code.trim())
        add(index, "code card missing code");
      if (typeof card.output !== "string") add(index, "code card missing output");
      if (typeof card.code === "string" && card.code.split("\n").length > 12)
        add(index, "code exceeds 12 lines");
    }
    if (!Array.isArray(card.relatedMisconceptions))
      add(index, "relatedMisconceptions must be an array");
    else if (card.relatedMisconceptions.some((item) => typeof item !== "string" || !item.trim()))
      add(index, "relatedMisconceptions contains an empty value");
    if (!Array.isArray(card.relatedChallengeIds) || !card.relatedChallengeIds.length)
      add(index, "relatedChallengeIds must contain at least one challenge");
    else {
      if (new Set(card.relatedChallengeIds).size !== card.relatedChallengeIds.length)
        add(index, "duplicate related challenge ID");
      if (card.relatedChallengeIds.some((id) => typeof id !== "string" || !id.trim()))
        add(index, "relatedChallengeIds contains an empty value");
      if (challengeIds && card.relatedChallengeIds.some((id) => !challengeIds.has(id)))
        add(index, "related challenge ID is not in the curriculum");
    }
  }
  return errors;
}
