import type { Flashcard, FlashcardType, Topic } from "../types";

type CardOptions = {
  difficulty?: 1 | 2 | 3;
  code?: string;
  output?: string;
  relatedMisconceptions?: string[];
};

function makeCard(
  id: string,
  topic: Topic,
  concept: string,
  type: FlashcardType,
  front: string,
  answer: string,
  explanation: string,
  relatedChallengeIds: string[],
  options: CardOptions = {},
): Flashcard {
  return {
    id,
    topic,
    concept,
    type,
    difficulty: options.difficulty ?? 1,
    front,
    answer,
    explanation,
    ...(options.code ? { code: options.code } : {}),
    ...(options.output !== undefined ? { output: options.output } : {}),
    relatedMisconceptions: options.relatedMisconceptions ?? [],
    relatedChallengeIds,
  };
}
const concept = (
  id: string,
  topic: Topic,
  name: string,
  front: string,
  answer: string,
  explanation: string,
  relatedChallengeIds: string[],
  options: CardOptions = {},
) =>
  makeCard(
    id,
    topic,
    name,
    "concept",
    front,
    answer,
    explanation,
    relatedChallengeIds,
    options,
  );

const code = (
  id: string,
  topic: Topic,
  name: string,
  front: string,
  answer: string,
  explanation: string,
  source: string,
  output: string,
  relatedChallengeIds: string[],
  options: Omit<CardOptions, "code" | "output"> = {},
) =>
  makeCard(
    id,
    topic,
    name,
    "code",
    front,
    answer,
    explanation,
    relatedChallengeIds,
    { ...options, code: source, output },
  );

